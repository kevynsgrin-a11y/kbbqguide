#!/usr/bin/env node
// Generates review/data.js from the media manifest for the Phase 10.6 human
// sign-off workbench. Embedding the data as a JS assignment (rather than fetch)
// lets review/index.html open directly over file:// without CORS issues.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { stdout } from 'node:process';

const manifest = JSON.parse(readFileSync('data/media-manifest.json', 'utf8'));

// Build usage context from recipe/guide/category/menu records.
const recipeTitles = {};
for (const f of readdirSync('src/content/recipes')) {
  if (!f.endsWith('.json')) continue;
  const r = JSON.parse(readFileSync(`src/content/recipes/${f}`, 'utf8'));
  recipeTitles[r.id] = r.title;
}
const guideText = readFileSync('src/lib/guides.ts', 'utf8');
const guideTitles = {};
for (const m of guideText.matchAll(/id: '(G\d+)',\s*\n\s*title: '([^']+)'/g))
  guideTitles[m[1]] = m[2];

function usageFor(asset) {
  const sr = asset.provenance.sourceRecord;
  if (asset.role === 'finished-dish-hero')
    return `Recipe hero — ${recipeTitles[sr] || sr}`;
  if (asset.role === 'guide-editorial-hero')
    return `Guide hero — ${guideTitles[sr] || sr}`;
  if (asset.role === 'category-editorial-hero') return `Category hero — ${sr}`;
  if (asset.role === 'menu-editorial-hero') return `Menu hero — ${sr}`;
  if (asset.role === 'brand-lifestyle-hero') return 'Home page hero';
  if (asset.role === 'brand-lifestyle-banner') return 'Home page lower banner';
  return `${asset.role} — ${sr}`;
}

const data = manifest.assets.map((a) => ({
  assetId: a.assetId,
  imageSrc: `../${a.path}`,
  role: a.role,
  usage: usageFor(a),
  currentAlt: a.altText,
  currentAltDecision: a.altDecision,
  proposedAlt: a.phase10Proposal?.proposedAlt ?? a.altText,
  proposedRole: a.phase10Proposal?.proposedRole ?? a.altDecision,
  roleRationale: a.phase10Proposal?.roleRationale ?? '',
  overclaimFlag: !!a.phase10Proposal?.overclaimFlag,
  overclaimNote: a.phase10Proposal?.overclaimNote ?? '',
  interimAltCorrectionApplied: !!a.phase10Proposal?.interimAltCorrectionApplied,
  visibleSummary: a.phase10Proposal?.visibleSummary ?? '',
  review: a.humanEditorialReview ?? { status: 'required', lanes: {} },
}));

const out = `// AUTO-GENERATED by scripts/build-review-data.mjs — do not edit by hand.
// Regenerate: npm run review:data
window.__REVIEW_DATA__ = ${JSON.stringify(data, null, 2)};
window.__REVIEW_LANES__ = ["food", "safety", "cultural", "accessibility", "brand"];
`;
writeFileSync('review/data.js', out);
stdout.write(`review/data.js written for ${data.length} assets\n`);
